"use client";

import { useState } from "react";
import { useFormState, useFormStatus } from "react-dom";
import SchoolPicker, { type SchoolOption } from "@/components/school-picker";
import ThaiDateField from "@/components/thai-date-field";
import { MEMBER_TYPES, MEMBER_TYPE_LABEL } from "@/lib/members";
import { createCode, updateCode, type CodeFormState } from "./actions";

export type CodeValues = { id?: string; parentId?: string; label: string; memberType: string; schoolId: string; expiresAt: string; maxUses: string; active: boolean; usedCount?: number };

const input = "min-h-11 w-full rounded-lg border border-neutral-300 bg-white px-3";

function Submit({ children }: { children: React.ReactNode }) {
  const { pending } = useFormStatus();
  return <button disabled={pending} className="min-h-11 rounded-lg bg-brand px-6 font-semibold text-white hover:bg-brand-dark disabled:opacity-50">{pending ? "กำลังบันทึก..." : children}</button>;
}

/** Create (no id) or edit one sign-up code. The code text itself is generated by the system. */
export default function CodeForm({ values, schools, parents = [], parentLabel }: { values: CodeValues; schools: SchoolOption[]; parents?: { id: string; label: string }[]; parentLabel?: string }) {
  const isNew = !values.id;
  const [state, action] = useFormState<CodeFormState, FormData>(isNew ? createCode : updateCode.bind(null, values.id!), undefined);
  const [isSub, setIsSub] = useState(!!values.parentId);
  const [schoolKey, setSchoolKey] = useState(0); // remounting the picker is how "clear school" works

  return (
    <form action={action} className="space-y-4 rounded-xl bg-white p-5 shadow-sm">
      <h2 className="font-semibold">{isNew ? "สร้างรหัสสมัครใหม่" : "แก้ไขรหัส"}</h2>
      <div className="grid gap-4 sm:grid-cols-2">
        <label className="block space-y-1 sm:col-span-2"><span className="text-sm font-medium">ป้ายกำกับ * (ไว้จำว่ารหัสนี้แจกใคร)</span><input name="label" required maxLength={100} defaultValue={values.label} placeholder="เช่น ครู รร.บ้านตัวอย่าง / นักเรียน ม.1" className={input} /></label>
        {isNew && parents.length > 0 && (
          <label className="block space-y-1 sm:col-span-2"><span className="text-sm font-medium">เป็นรหัสย่อยของรหัสกลุ่ม (ไม่บังคับ — เว้นว่าง = รหัสกลุ่มใหญ่/รหัสเดี่ยว)</span>
            <select name="parentId" defaultValue={values.parentId ?? ""} onChange={(e) => setIsSub(!!e.target.value)} className={input}>
              <option value="">— ไม่ใช่รหัสย่อย —</option>
              {parents.map((p) => <option key={p.id} value={p.id}>{p.label}</option>)}
            </select>
            <span className="block text-xs text-neutral-500">รหัสย่อยใช้ประเภทสมาชิกของรหัสกลุ่ม และถูกจำกัดด้วยรหัสกลุ่ม (ปิด/หมดอายุ/ครบจำนวน)</span>
          </label>
        )}
        {!isNew && parentLabel && <p className="rounded-lg bg-neutral-50 px-3 py-2 text-sm sm:col-span-2">รหัสย่อยของ: <strong>{parentLabel}</strong> (ประเภทสมาชิกเปลี่ยนที่รหัสกลุ่ม)</p>}
        {isSub || parentLabel ? <input type="hidden" name="memberType" value={values.memberType} /> : (
          <label className="block space-y-1"><span className="text-sm font-medium">ประเภทสมาชิกที่ได้</span>
            <select name="memberType" defaultValue={values.memberType} className={input}>{MEMBER_TYPES.map((t) => <option key={t} value={t}>{MEMBER_TYPE_LABEL[t]}</option>)}</select>
          </label>
        )}
        <label className="block space-y-1"><span className="text-sm font-medium">ใช้ได้กี่ครั้ง (เว้นว่าง = ไม่จำกัด)</span><input name="maxUses" inputMode="numeric" pattern="[0-9]*" defaultValue={values.maxUses} placeholder="เช่น 40" className={input} /></label>
        <div className="space-y-1 sm:col-span-2">
          <span className="text-sm font-medium">ล็อกโรงเรียน (ไม่บังคับ — ทุกคนที่ใช้รหัสนี้จะอยู่โรงเรียนนี้)</span>
          <div className="flex items-start gap-2">
            <div className="min-w-0 flex-1"><SchoolPicker key={schoolKey} schools={schools} defaultValue={schoolKey === 0 ? values.schoolId : ""} /></div>
            <button type="button" onClick={() => setSchoolKey((k) => k + 1)} className="min-h-11 shrink-0 rounded-lg border border-neutral-300 px-3 text-sm">ไม่ล็อก</button>
          </div>
        </div>
        <div className="sm:col-span-2"><ThaiDateField name="expiresAt" label="หมดอายุ (พ.ศ. — ว่างได้ = ไม่หมดอายุ)" withTime defaultValue={values.expiresAt} defaultTime={{ hour: 23, minute: 59 }} /></div>
      </div>
      {!isNew && <label className="flex min-h-11 items-center gap-2"><input type="checkbox" name="active" defaultChecked={values.active} className="h-4 w-4" /> เปิดใช้งานรหัสนี้</label>}
      {state?.error && <p role="alert" className="text-sm text-red-600">{state.error}</p>}
      {state?.saved && <p role="status" className="text-sm text-green-700">{isNew ? "สร้างรหัสแล้ว — ดูในรายการด้านล่าง" : "บันทึกแล้ว"}</p>}
      <Submit>{isNew ? "สร้างรหัส" : "บันทึก"}</Submit>
    </form>
  );
}
